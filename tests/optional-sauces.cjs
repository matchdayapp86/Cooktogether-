const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const match=html.match(/window\.COOK_RECIPES = (\[[\s\S]*?\]);\s*window\.COOK_LEGACY_RECIPES = /);
assert(match,'Recipes could not be found in index.html');
const recipes=JSON.parse(match[1]);
const originals=JSON.parse(JSON.stringify(recipes));
assert.equal(recipes.length,116,'Audit has to be updated if the recipe inventory changes');
const context={window:{COOK_RECIPES:recipes}};
vm.runInNewContext(fs.readFileSync('optional-sauces.js','utf8'),context,{filename:'optional-sauces.js'});
const audit=context.window.COOK_SAUCE_AUDIT;
assert.equal(audit.total,116);
assert.equal(audit.added,14);
assert.equal(audit.all.length,15);
assert.equal(new Set(audit.all).size,15);
assert.equal(audit.all.includes('chicken-roast'),true);
for (const [index,recipe] of recipes.entries()){
 const original=originals[index];
 assert.equal(recipe.id,original.id);
 const oldCopy={...original};delete oldCopy.optionalSauce;
 const newCopy={...recipe};delete newCopy.optionalSauce;
 assert.deepEqual(newCopy,oldCopy,recipe.id+' original main ingredients, steps or cooking times changed');
 if(!recipe.optionalSauce)continue;
 const option=recipe.optionalSauce;
 assert(option.title.startsWith('Optional '));
 assert(option.status.includes('NOT yet kitchen-tested')||option.status.includes('not yet kitchen-tested'));
 assert(Array.isArray(option.ingredients)&&option.ingredients.length>=1);
 assert(option.ingredients.every(row=>row.length===5&&row[2]>0&&row[3]&&row[4]));
 assert(option.task?.optionalSauce);
 assert(option.task.instructions.length>75);
 assert(option.task.check.length>20);
 assert(option.task.uses.length===0);
 const insertion=recipe.beginnerTasks.findIndex(t=>t.title===option.beforeTitle);
 assert(insertion>=0,'Sauce anchor no longer exists in '+recipe.id);
 assert(insertion>0,'Sauce needs to be after actual cooking, not first in '+recipe.id);
 // The recipe's authored steps are not rewritten or omitted; one guided sauce step is added.
 const withSauce=[...recipe.beginnerTasks.slice(0,insertion),option.task,...recipe.beginnerTasks.slice(insertion)];
 assert.equal(withSauce.length,original.beginnerTasks.length+1);
 assert.equal(withSauce[insertion+1].title,option.beforeTitle);
 assert.equal(withSauce.filter(t=>t.optionalSauce).length,1);
 if(recipe.id!=='chicken-roast')assert(option.reference?.startsWith('https://'));
}
assert(html.indexOf('<script src="optional-sauces.js')>html.indexOf('window.COOK_DAYS = '));
assert(html.indexOf('<script src="optional-sauces.js')<html.indexOf('const RECIPES = window.COOK_RECIPES'));
assert(html.includes("if(r.optionalSauce&&guideId===r.id&&state.cookAlong?.[key]?.sauce===true)"));
assert(html.includes("const insertion=tasks.findIndex(t=>t.title===r.optionalSauce.beforeTitle)"));
assert(html.includes("if(!recipeById(guideId)?.optionalSauce)return"));
assert(html.includes('data-action="guide-sauce-shopping"'));
assert(html.includes("const existing=state.manual.find(item=>item.id===key)"));
assert(html.includes('Published pairing reference'));
assert(html.includes('These extras are not automatically included in the meal plan shopping list'));
assert(!html.includes("guideId!=='chicken-roast'"),'Chicken-only selection restriction returned');
console.log('Reviewed '+recipes.length+' recipes, '+audit.all.length+' opt-in sauces, '+audit.added+' new pairings.');
console.log('Anchored Cook Along stage, unchanged main ingredients/steps/times, shopping hook, and references passed.');
